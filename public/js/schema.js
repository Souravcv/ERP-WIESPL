export function fieldMap(entity) {
  return Object.fromEntries(ENTITIES[entity].fields.map(f => [f.key, f]));
}

export function canWrite(entity, role) {
  if (role === 'admin') return true;
  return (ENTITIES[entity]?.write || []).includes(role);
}
