export function seed() {
  // Settings: add any defaults that are missing, never overwrite edits.
  const current = getSettings();
  const missing = Object.fromEntries(Object.entries(DEFAULT_SETTINGS).filter(([k]) => !(k in current)));
  if (Object.keys(missing).length) setSettings(missing);
  // Company GSTIN as printed on WIESPL purchase orders, if not entered yet.
  if (!getSettings().gstin) setSettings({ gstin: '27AAACW3993K1ZR' });

  if (!db.prepare('SELECT COUNT(*) c FROM products').get().c) {
    const st = db.prepare(`INSERT INTO products (sort, code, name, kind, category, uom, qty_basis, default_qty, install_pct, description, rate, hsn, gst_rate, active, created_by)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, '', 18, 'Yes', 'system')`);
    for (const p of P) st.run(...p);
  }

  // WIESPL control panel range (V1–V5): added once by product code, never overwriting an edited product
  const hasCode = db.prepare('SELECT 1 FROM products WHERE code = ?');
  const addPanel = db.prepare(`INSERT INTO products (sort, code, name, kind, category, uom, qty_basis, default_qty, install_pct, description, rate, hsn, gst_rate, active, created_by)
    VALUES (?, ?, ?, 'Item', 'Control Panels', 'Each', 'manual', 1, 0, ?, 0, '', 18, 'Yes', 'system')`);
  PANELS.forEach((p, i) => { if (!hasCode.get(p.code)) addPanel.run(91 + i, p.code, `WIESPL ${p.name} (V${i + 1})`, panelSpec(p)); });

  if (!db.prepare('SELECT COUNT(*) c FROM users').get().c) {
    // On hosts without file access (e.g. Render) set ADMIN_PASSWORD in the environment instead.
    if (process.env.ADMIN_PASSWORD) {
      db.prepare('INSERT INTO users (username, name, role, pass_hash, must_change) VALUES (?, ?, ?, ?, 0)')
        .run('admin', 'Administrator', 'admin', hashPassword(process.env.ADMIN_PASSWORD));
      console.log('\n  First run: admin login created with the ADMIN_PASSWORD environment variable.\n');
      return;
    }
    const pw = crypto.randomBytes(6).toString('base64url');
    db.prepare('INSERT INTO users (username, name, role, pass_hash, must_change) VALUES (?, ?, ?, ?, 1)')
      .run('admin', 'Administrator', 'admin', hashPassword(pw));
    const file = path.join(DATA_DIR, 'initial-admin-password.txt');
    fs.writeFileSync(file, `WIESPL CRM first login\nusername: admin\npassword: ${pw}\n\nYou will be asked to change it after logging in. Delete this file afterwards.\n`);
    console.log(`\n  First run: admin login created. Credentials saved in ${file}\n`);
  }
}
